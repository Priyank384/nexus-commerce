CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(32),
    created_datetime TIMESTAMP(6) NOT NULL,
    updated_datetime TIMESTAMP(6),
    deleted_datetime TIMESTAMP(6),
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

ALTER TABLE orders
    ADD COLUMN user_id BIGINT NOT NULL,
    ADD CONSTRAINT fk_order_user FOREIGN KEY (user_id) REFERENCES users (id);

ALTER TABLE reviews
    ADD COLUMN user_id BIGINT NOT NULL,
    ADD CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES users (id);
