-- Apparel variants: every product becomes a family of size+color SKUs with independent
-- stock and price delta. Historic products without variants get a synthetic 'ONE / Default'
-- row so their existing orders, cart lines, and wishlist entries can point at a real variant.
--
-- Soft-delete-safe uniqueness uses the same generated-column trick as V8/V13: the expression
-- yields NULL for deleted rows and NULLs are distinct in a PostgreSQL unique index.

CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL,
    sku VARCHAR(64) NOT NULL,
    size VARCHAR(20) NOT NULL,
    color_name VARCHAR(60) NOT NULL,
    color_hex VARCHAR(9) NOT NULL,
    price_delta NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    image_url VARCHAR(255) NULL,
    stock INT NOT NULL DEFAULT 0,
    created_datetime TIMESTAMP(6) NOT NULL,
    updated_datetime TIMESTAMP(6) NULL,
    deleted_datetime TIMESTAMP(6) NULL,
    live_sku VARCHAR(64) GENERATED ALWAYS AS
        (CASE WHEN deleted_datetime IS NULL THEN sku ELSE NULL END) STORED,
    live_product_option VARCHAR(120) GENERATED ALWAYS AS
        (CASE WHEN deleted_datetime IS NULL
              THEN (product_id::text || '|' || LOWER(size) || '|' || LOWER(color_name))
              ELSE NULL END) STORED,
    CONSTRAINT pk_product_variants PRIMARY KEY (id),
    CONSTRAINT fk_pv_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE UNIQUE INDEX uk_pv_live_sku ON product_variants (live_sku);
CREATE UNIQUE INDEX uk_pv_live_product_option ON product_variants (live_product_option);
CREATE INDEX idx_pv_product ON product_variants (product_id);
CREATE INDEX idx_pv_size ON product_variants (size);
CREATE INDEX idx_pv_color ON product_variants (color_name);

-- Backfill: one 'ONE / Default' variant per existing product, sku = LEGACY-<6-digit id>.
-- Stock mirrors products.stock so V9's inventory semantics carry over untouched.
INSERT INTO product_variants (
    product_id, sku, size, color_name, color_hex,
    price_delta, image_url, stock, created_datetime
)
SELECT
    p.id,
    CONCAT('LEGACY-', LPAD(p.id::text, 6, '0')),
    'ONE',
    'Default',
    '#0F0F0F',
    0.00,
    p.image,
    COALESCE(p.stock, 0),
    LOCALTIMESTAMP
FROM products p;
