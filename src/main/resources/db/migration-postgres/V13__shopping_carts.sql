-- Persistent shopping carts, one live cart per user. Checkout converts the cart into an
-- Order (reusing all stock/snapshot logic) and clears it. Line items are the cart-only
-- state, not order snapshots; they always reflect the current catalogue at checkout time.
--
-- Live-row uniqueness is expressed as a CREATE UNIQUE INDEX on the generated column rather
-- than an inline table constraint, which keeps the generated-column definition and the
-- uniqueness rule in separate statements.
CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    created_datetime TIMESTAMP(6) NOT NULL,
    updated_datetime TIMESTAMP(6) NULL,
    deleted_datetime TIMESTAMP(6) NULL,
    -- Uniqueness applies only to live rows so a soft-deleted cart frees the slot.
    live_user_id BIGINT GENERATED ALWAYS AS
        (CASE WHEN deleted_datetime IS NULL THEN user_id ELSE NULL END) STORED,
    CONSTRAINT pk_carts PRIMARY KEY (id),
    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX uk_carts_live_user ON carts (live_user_id);
CREATE INDEX idx_carts_user ON carts (user_id);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    created_datetime TIMESTAMP(6) NOT NULL,
    updated_datetime TIMESTAMP(6) NULL,
    deleted_datetime TIMESTAMP(6) NULL,
    -- Live (cart_id, product_id) pairs are unique; deleted rows don't consume the slot.
    -- || over textcasts rather than concat(): concat() is STABLE and cannot back a
    -- generated column.
    live_pair VARCHAR(64) GENERATED ALWAYS AS
        (CASE WHEN deleted_datetime IS NULL THEN (cart_id::text || '-' || product_id::text) ELSE NULL END) STORED,
    CONSTRAINT pk_cart_items PRIMARY KEY (id),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);

CREATE UNIQUE INDEX uk_cart_items_live_pair ON cart_items (live_pair);
CREATE INDEX idx_cart_items_cart ON cart_items (cart_id);
CREATE INDEX idx_cart_items_product ON cart_items (product_id);
